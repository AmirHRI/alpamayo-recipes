"""Small, mmap-friendly cache of full-teacher action rollouts.

Each entry stores ``states[K, M + 1, T, C]`` in the repository flow-matching
order: state 0 is the sampled noise at ``s=0`` and state ``M`` is the result
after the last Euler step at ``s=1``.  Keeping the states (rather than rounded
velocities) lets consistency training compare the exact endpoints generated by
the full Alpamayo teacher.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import torch

from alpamayo1_5_distill.data import kv_cache_io


FORMAT = "alpamayo_full_teacher_action_rollout_v1"
TIER = "action_rollouts"


def entry_path(cache_root: str | Path, key: str) -> Path:
    return kv_cache_io.entry_path(cache_root, TIER, key)


def has_entry(cache_root: str | Path, key: str) -> bool:
    return kv_cache_io.has_entry(cache_root, TIER, key)


def save_states(
    cache_root: str | Path,
    key: str,
    states: torch.Tensor,
    metadata: dict[str, Any] | None = None,
) -> Path:
    """Atomically store one full-teacher rollout in float32.

    Float32 is intentional: a transition is the difference between adjacent
    O(1) states.  Saving bf16 would quantize that difference before the endpoint
    loss ever sees it, especially near the data end of a finer grid.
    """
    if states.ndim != 4:
        raise ValueError(f"states must be [K,M+1,T,C], got {tuple(states.shape)}")
    if states.shape[0] < 1 or states.shape[1] < 2:
        raise ValueError(f"states needs K>=1 and M>=1, got {tuple(states.shape)}")
    states = states.detach().to(device="cpu", dtype=torch.float32).contiguous()
    if not bool(torch.isfinite(states).all()):
        raise ValueError("refusing to cache non-finite teacher states")
    meta = dict(metadata or {})
    meta.update(
        format=FORMAT,
        num_noise=int(states.shape[0]),
        num_steps=int(states.shape[1] - 1),
        action_tokens=int(states.shape[2]),
        action_channels=int(states.shape[3]),
    )
    return kv_cache_io.save_entry(cache_root, TIER, key, {"states": states}, meta)


def load_states(cache_root: str | Path, key: str) -> torch.Tensor:
    """Mmap-read one ``[K,M+1,T,C]`` float32 rollout tensor."""
    out = kv_cache_io.load_entry(cache_root, TIER, key, names=("states",))
    if "states" not in out:
        raise KeyError(f"teacher rollout for {key!r} has no 'states' tensor")
    states = out["states"]
    if states.ndim != 4:
        raise ValueError(
            f"cached teacher states for {key!r} must be [K,M+1,T,C], "
            f"got {tuple(states.shape)}"
        )
    return states


def write_index(
    cache_root: str | Path,
    entries: dict[str, int],
    metadata: dict[str, Any],
    shard: int,
) -> Path:
    """Write per-shard provenance; cache files remain the source of truth."""
    root = Path(cache_root)
    root.mkdir(parents=True, exist_ok=True)
    path = root / f"action_rollouts.index.shard{int(shard)}.json"
    tmp = path.with_suffix(".json.tmp")
    with tmp.open("w", encoding="utf-8") as f:
        json.dump({"metadata": metadata, "entries": entries}, f, indent=2)
    tmp.rename(path)
    return path


def tier_stats(cache_root: str | Path) -> dict[str, int | float]:
    root = Path(cache_root) / TIER
    sizes = (
        [p.stat().st_size for p in root.glob("*/*.safetensors")]
        if root.exists()
        else []
    )
    total = sum(sizes)
    return {
        "n_entries": len(sizes),
        "bytes": total,
        "kb_per_entry": (total / len(sizes) / 1024) if sizes else 0.0,
    }
